    /**
     * 微信授权配置.
     * @auth true
     * @menu true
     * @throws \think\admin\Exception
     */
    public function options()
    {
        $this->vo = AdminService::getSite('wechatcfg',[]);
        $this->thrNotify = sysuri('wechat/api.push/index', [], false, true);
        $service_authurl = url('service/api.push/auth',[],false,true) . '?source=SOURCE';
        if ($this->request->isGet()) {
            try {
                // 生成微信授权链接
                $source = enbase64url(sysuri('admin/index/index', [], false, true) . '#' . $this->request->url());
                $this->authurl = str_replace('source=SOURCE', "source={$source}",  $service_authurl);

                // 授权成功后的参数保存
                if (input('?appid') && input('?appkey')) {
                    $this->vo['type'] = 'thr';
                    $this->vo['thr_appid'] =  input('appid');
                    $this->vo['thr_appkey'] =  input('appkey');
                    AdminService::setSite('wechatcfg',$this->vo);
                    WechatService::ThinkServiceConfig()->setApiNotifyUri($this->thrNotify);
                }
                // 读取授权的微信参数
                $this->wechat = WechatService::ThinkServiceConfig()->getConfig();
            } catch (\Exception $exception) {
                $this->wechat = [];
                $this->message = $exception->getMessage();
            }

            $this->geoip = $this->app->cache->get('mygeoip', '');
            if (empty($this->geoip)) {
                $this->geoip = gethostbyname($this->request->host());
                $this->app->cache->set('mygeoip', $this->geoip, 360);
            }
            $this->title = '微信授权配置';
            $this->fetch();
        } else {
            $config = array_merge((array)$this->vo, $this->request->post('config',[]));
            if ($config['type'] === 'thr') {
                try {
                    WechatService::ThinkServiceConfig()->setApiNotifyUri($this->thrNotify);
                } catch (\Exception $exception) {
                    $this->error($exception->getMessage());
                }
            }
            sysoplog('微信授权配置', '修改微信授权配置成功');
            $this->success('微信授权修改成功！', admuri('', ['uniqid' => uniqid()]));
        }
    }


    /**
     * 上传代码到体验版本
     * @return void
     */
    public function submit_code(): void
    {
        $map = $this->_vali([
            'templateId.require'   => '请选择上传的模版',
        ]);

        $appid = AdminService::getSite('wechatcfg.thr_appid','');
        if (empty($appid)) $this->error('公众号错误');

        $temp = ServiceTemplate::mk()->where(['id' => $map['templateId']])->findOrEmpty();
        if ($temp->isEmpty()) $this->error('模版信息不存在');

        $extJson = json_encode([
            'extEnable' => true,
            'extAppid' => 'wxa81609e357681a00',
            'directCommit' => false,
            'ext' => [
                'API_BASE' => $this->request->domain() . '/',
                'SITE_ID' => (string)$this->site_id
            ]
        ],JSON_UNESCAPED_UNICODE);

        try {
            $result = AuthService::WeMiniCode($appid)->commit($temp->getAttr('template_id') , $extJson, $temp->getAttr('user_version'), $temp->getAttr('user_desc'));
            if (empty($result['errcode']) && $result['errmsg'] === 'ok') {
                $this->success('操作成功');
            } else {
                throw new Exception('上传模版失败，请稍候再试！');
            }
        } catch (LocalCacheException|InvalidResponseException|Exception $exception) {
            $this->error($exception->getMessage());
        }
    }

    /**
     * 审核-提交
     * @return void
     */
    public function audit_submit(): void
    {
        $appid = AdminService::getSite('wechatcfg.thr_appid','');
        $miniCode  = AuthService::WeMiniCode($appid);
        if ($this->request->isPost()){
            $page = $this->request->post('page');
            $data = $this->request->post('data');
            $cate = json_decode(CodeExtend::deSafe64($this->request->post('cate')),true);
            if (empty($cate)) $this->error('请选择类目');

            $data['item_list'][] = [
                "address"       => $page,
                "tag"           => "",
                "first_class"   => $cate['first_class'],
                "second_class"  => $cate['second_class'],
                "first_id"      => (int)$cate['first_id'],
                "second_id"     => (int)$cate['second_id'],
                "title"         => "首页"
            ];

            $preview_info = Cache::get('preview_info');
            if (empty($preview_info)){
                [$medias,$videoList ,$picList] = [sysdata('service.arraign'),[],[]];
                foreach ($medias as $media)  try {
                    $filename = LocalStorage::instance()->path($media['filepath'],true);
                    if (!LocalStorage::instance()->has($media['filepath'],true)){
                        throw new Exception("审核文件{$media['filepath']}不存在");
                    }
                    $result = $miniCode->uploadmedia($filename);
                    if (empty($result['errcode']) && $result['errmsg'] === 'ok') {
                        if ( $result['type'] == 'image'){
                            $picList[] = $result['mediaid'];
                        }else if( $result['type'] == 'video' ){
                            $videoList[] = $result['mediaid'];
                        }
                    }else{
                        throw new Exception('提交审核失败，请稍候再试！');
                    }
                } catch (Exception $exception) {
                    $this->error($exception->getMessage().'；code:'. $exception->getCode());
                }
                $preview_info = [
                    'video_id_list' => $videoList,
                    'pic_id_list' => $picList
                ];
                Cache::set('preview_info',$preview_info,86000*3);
            }

            $data['preview_info'] = $preview_info;

            try {
                $wechatcfg = AdminService::getSite('wechatcfg',[]);
                $result = $miniCode->submitAudit($data);
                if (empty($result['errcode']) && $result['errmsg'] === 'ok') {
                    $wechatcfg['auditid'] = $result['auditid'];
                    AdminService::setSite('wechatcfg',$wechatcfg);
                    $this->success('审核提交成功');
                }else{
                    throw new Exception('提交审核失败，请稍候再试！');
                }
            } catch (Exception $exception) {
                $this->error($exception->getMessage().'；code:'. $exception->getCode());
            }
        }else{
            // 获取小程序页面
            try {
                // 获取小程序类目
                $page = $miniCode->getPage();
                if (empty($page['errcode']) && $page['errmsg'] === 'ok') {
                    $this->page_list = $page['page_list']??[];
                } else {
                    throw new Exception('代码页面列表获取失败，请稍候再试！');
                }
                // 获取小程序类目
                $cate = $miniCode->getCategory();
                if (empty($cate['errcode']) && $cate['errmsg'] === 'ok') {
                    $this->cate_list = $cate['category_list']??[];
                    foreach ($this->cate_list as &$vo){
                        $vo['value'] = CodeExtend::enSafe64(json_encode($vo,JSON_UNESCAPED_UNICODE));
                    }
                } else {
                    throw new Exception('类目名称信息获取失败，请稍候再试！');
                }
            } catch (LocalCacheException|InvalidResponseException|Exception $exception) {
                $this->error($exception->getMessage());
            }
//
            $this->vo['order_path'] = 'familyGroup/family/list';  //小程序订单中心path
            $this->vo['page'] = $this->page_list[0]??'';  //小程序订单中心path
            $this->fetch();

        }

    }

    /**
     * 审核-撤销
