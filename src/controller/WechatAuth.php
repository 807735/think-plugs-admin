    /**
     * 小程序检测数据
     * @return void
     * @throws InvalidResponseException
     * @throws LocalCacheException
     */
    public function serverConfig(): void
    {
        if ($this->request->isGet()){
            $this->check = [
                'server' =>['name' => '服务器域名','data' => [],'msg' => '检查通过','status' => 1],
                'webview' =>['name' => '业务域名','data' => [],'msg' => '检查通过','status' =>1],
            ];
            $domain = AuthService::WeMiniDomain(AdminService::getSite('wechatcfg.thr_appid',''));
            foreach ($domain->modifyDomain('get') as $key => $val) if (in_array($key,['requestdomain','uploaddomain','downloaddomain'])) {
                $name = ['requestdomain' => 'request','uploaddomain' => 'uploadFile','downloaddomain' => 'downloadFile'][$key];
                $this->check['server']['data'][$key] =  ['name' => $name,'list' => $val];

                if ($this->check['server']['status'] == 1 && !in_array($this->http,$val) ){
                    $this->check['server']['status'] = 0;
                    $this->check['server']['msg'] = "{$name} 域名检测未通过";
                }
            }
            foreach ($domain->setWebViewDomain('get') as $key => $val) if (in_array($key,['webviewdomain'])) {
                $name = ['webviewdomain' => 'webview'][$key];
                $this->check['webview']['data'][$key] = ['name' => $name,'list' => $val];
                if ($this->check['webview']['status'] == 1 && !in_array($this->http,$val) ){
                    // pr($http, $this->check['webview'] , in_array($http,$val));
                    $this->check['webview']['status'] = 0;
                    $this->check['webview']['msg'] = "{$name} 域名检测未通过";
                }
            }


            $this->fetch();
        }else{
            $action = $this->request->get('action');
            switch ($action){
                case 'domain':  // 服务器域名同步覆盖
                    $domain = AuthService::WeMiniDomain(AdminService::getSite('wechatcfg.thr_appid',''));
                    $type = $this->request->get('type');
                    try {
                        if ($type == 'server'){
                            $domain->modifyDomain('set',[
                                'requestdomain' => [$this->http],
                                'uploaddomain' => [$this->http],
                                'downloaddomain' => [$this->http],
                            ]);
                        }
                        if ($type == 'webview'){
                            $domain->setWebViewDomain('set',[
                                'webviewdomain' => [$this->http],
                            ]);
                        }
                        $this->success('操作成功');
                    } catch (LocalCacheException|InvalidResponseException|Exception $exception) {
                        $this->error($exception->getMessage());
                    }
                    break;
            }
        }

    }


    /**
     * 异步获取版本信息
     * @return void
     * @throws InvalidResponseException
     * @throws LocalCacheException
     */
    public function getTrialVersion(): void
    {

        $this->wechat = WechatService::ThinkServiceConfig()->getConfig();
        $miniCode  = AuthService::WeMiniCode($this->wechat['authorizer_appid']);

        $this->templates = ServiceTemplate::mk()->where(['type' => 'temp'])->order('create_time desc')->select()->toJson();

        // 获取体验二维码
        $this->qrcode  = 'data:image/png;base64,'. base64_encode($miniCode->getQrcode()) ;

        try {
            // 获取版本信息
            $version = $miniCode->getVersioninfo();
            if (empty($version['errcode']) && $version['errmsg'] === 'ok') {
                $this->version = $version;
            } else {
                throw new Exception('审核状态获取失败，请稍候再试！');
            }
        } catch (LocalCacheException|InvalidResponseException|Exception $exception) {
            $this->error($exception->getMessage());
        }

        try {
            // 获取审核状态
            $audit = $miniCode->getLatestAuditatus();
            if (empty($audit['errcode']) && $audit['errmsg'] === 'ok') {
                if (isset($audit['screenshot']) && !empty($audit['screenshot'])){
                    $audit['screenshot'] = str2arr($audit['screenshot'],'|');
                }
                $this->audit = $audit;
            } else {
                throw new Exception('审核状态获取失败，请稍候再试！');
            }

        } catch (LocalCacheException|InvalidResponseException|Exception $exception) {
        }
        $this->fetch();
    }

    /**
     * 绑定小程序.
     * @auth true
     * @throws \think\admin\Exception
     */
    public function options_wxapp()
    {
        if ($this->request->isGet()) {
            $data = sysdata('plugin.wechat.wxapp') ?: [];
            Builder::mk()
                ->addTextInput('appid', '小程序', 'AppId', true, '<b>必选</b>，微信小程序 AppID 需要微信公众号平台获取！', '^wx[0-9a-z]{16}$', ['maxlength' => 18])
                ->addTextInput('appkey', '小程序密钥', 'AppSecret', true, '<b>必选</b>，微信小程序 AppSecret 需要微信公众号平台获取！', '^[0-9a-z]{32}$', ['maxlength' => 32])
                ->addSubmitButton('保存参数')->addCancelButton()
                ->fetch(['vo' => ['appid' => $data['appid'] ?? '', 'appkey' => $data['appkey'] ?? '']]);
        } else {
            sysdata('plugin.wechat.wxapp', $this->_vali([
                'appid.require' => '小程序ID不能为空！',
                'appkey.require' => '小程序密钥不能为空！',
            ]));
            $this->success('参数保存成功！');
        }
    }


